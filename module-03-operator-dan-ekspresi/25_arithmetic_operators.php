<?php
// Operator aritmetika standar di PHP untuk kalkulasi matematika:
// +, -, *, /, %, ** (eksponensial/pangkat)

$a = 14;
$b = 4;

echo "Operasi Penjumlahan (14 + 4) : " . ($a + $b) . "\n";
echo "Operasi Pengurangan (14 - 4) : " . ($a - $b) . "\n";
echo "Operasi Perkalian   (14 * 4) : " . ($a * $b) . "\n";
echo "Operasi Pembagian   (14 / 4) : " . ($a / $b) . "\n";
echo "Modulus/Sisa Bagi   (14 % 4) : " . ($a % $b) . "\n";
echo "Eksponensial        (14 ** 4): " . ($a ** $b) . "\n";
